"""Download/prepare Parakh's approved data sources.
Run from the Parakh project root.

Internet is required. This script intentionally does not synthesize transactions.
"""
from pathlib import Path
import urllib.request
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public' / 'data' / 'india_sources'
OUT.mkdir(parents=True, exist_ok=True)

HF_UPI = 'https://huggingface.co/datasets/prasad-gade05/india-upi-ecosystem-2018-2025/resolve/main/data/train-00000-of-00001.parquet'
UPI_OUT = OUT / 'india_upi_ecosystem_2018_2025.parquet'

print('Downloading India UPI Ecosystem dataset...')
try:
    urllib.request.urlretrieve(HF_UPI, UPI_OUT)
    print(f'Saved: {UPI_OUT}')
except Exception as exc:
    print('Could not download UPI dataset automatically:', exc)
    print('Use the Hugging Face dataset page listed in DATASET_MANIFEST.md and place the parquet here:')
    print(UPI_OUT)

print('\nOlist: place the official CSV files in public/data/raw/ from the Kaggle Olist dataset.')
print('RBI: download the official Payment System Indicators files from RBI and place them in public/data/india_sources/rbi/.')
print('\nNo synthetic transactions are generated by this script.')
